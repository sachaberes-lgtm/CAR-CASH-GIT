VIDE = ([(0x1F000,0x1FAFF),(0x2600,0x27BF),(0x2300,0x23FF),(0x2B00,0x2BFF),(0xFE0E,0xFE0F),(0x200D,0x200D),(0x20E3,0x20E3)])
glyphs={'.notdef':None,'vide':None}; cmap={}; adv={'.notdef':1000,'vide':0}
def carre(pen,x0,y0,x1,y1):
    pen.moveTo((x0,y0));pen.lineTo((x0,y1));pen.lineTo((x1,y1));pen.lineTo((x1,y0));pen.closePath()
for cp,rows in G.items():
    n='u%04X'%cp; pen=TTGlyphPen(None)
    for r,row in enumerate(rows):
        c=0
        while c<7:
            if row[c]=='#':
                d=c
                while d<7 and row[d]=='#': d+=1
                carre(pen,c*125,1000-125*(r+1),d*125,1000-125*r); c=d
            else: c+=1
    glyphs[n]=pen.glyph(); cmap[cp]=n; adv[n]=1000
glyphs['.notdef']=TTGlyphPen(None).glyph(); glyphs['vide']=TTGlyphPen(None).glyph()
for a,b in VIDE:
    for cp in range(a,b+1):
        if cp not in cmap: cmap[cp]='vide'
order=['.notdef','vide']+[k for k in glyphs if k not in('.notdef','vide')]
fb=FontBuilder(1000,isTTF=True); fb.setupGlyphOrder(order); fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs); fb.setupHorizontalMetrics({k:(adv.get(k,1000),0) for k in order})
fb.setupHorizontalHeader(ascent=1000,descent=0); fb.setupNameTable({'familyName':'CC Symboles','styleName':'Regular'})
fb.setupOS2(sTypoAscender=1000,sTypoDescender=0,usWinAscent=1000,usWinDescent=374); fb.setupPost()
fb.font.flavor='woff2'; import os;fb.save(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','..','VERSION PRINCIPALE','assets','fonts','ccsymboles.woff2')); print('ok',len(cmap),'codes')
